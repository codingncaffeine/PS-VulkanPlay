#!/usr/bin/env python3
"""Writes src/proto/key_tables.inc from the reference implementation's source.

A console only understands a client that uses the same fixed tables it does.
They are interoperability data and are necessarily identical in every
implementation. This script takes them from chiaki-ng's lib/src/rpcrypt.c (the
checkout that tools/oracle/run.sh fetches) so that the file can be regenerated
and compared whenever the pinned commit moves.

    tools/oracle/extract-key-tables.py REFERENCE_DIR OUTPUT_FILE
"""
import hashlib
import pathlib
import re
import subprocess
import sys

# our name -> (name in the reference, expected size)
TABLES = {
    "kRegistKeys0Ps4": ("ps4_keys_0", 512),
    "kRegistKeys0Ps5": ("ps5_keys_0", 512),
    "kRegistKeys1Ps4": ("ps4_keys_1", 512),
    "kRegistKeys1Ps5": ("ps5_keys_1", 512),
    "kAuthKeysAPs4": ("keys_a_ps4", 0x70 * 0x20),
    "kAuthKeysAPs5": ("keys_a_ps5", 0x70 * 0x20),
    "kAuthKeysBPs4": ("keys_b_ps4", 0x70 * 0x20),
    "kAuthKeysBPs5": ("keys_b_ps5", 0x70 * 0x20),
    "kIvKeyPs4": ("hmac_key_ps4", 16),
    "kIvKeyPs5": ("hmac_key_ps5", 16),
}


def main() -> int:
    reference = pathlib.Path(sys.argv[1])
    output = pathlib.Path(sys.argv[2])
    source = (reference / "lib/src/rpcrypt.c").read_text()
    commit = subprocess.run(["git", "-C", str(reference), "rev-parse", "HEAD"], check=True,
                            capture_output=True, text=True).stdout.strip()

    found: dict[str, list[bytes]] = {}
    pattern = re.compile(r"const uint8_t (\w+)\[[^\]]*\]\s*=\s*\{([^}]*)\}", re.S)
    for name, body in pattern.findall(source):
        body = re.sub(r"//[^\n]*", "", body)
        values = bytes(int(token, 0) for token in re.findall(r"0x[0-9a-fA-F]+|\d+", body))
        found.setdefault(name, []).append(values)

    lines = [
        "// Generated by tools/oracle/extract-key-tables.py; do not edit by hand.",
        "//",
        "// Fixed tables that every Remote Play client must use to be understood by a",
        "// console. They are interoperability data, the same in every implementation.",
        f"// Taken from chiaki-ng, lib/src/rpcrypt.c, commit {commit}.",
        "",
    ]
    for ours, (theirs, size) in TABLES.items():
        copies = found.get(theirs)
        if not copies:
            raise SystemExit(f"{theirs}: not found in the reference")
        if any(copy != copies[0] for copy in copies):
            raise SystemExit(f"{theirs}: the reference holds copies that differ")
        table = copies[0]
        if len(table) != size:
            raise SystemExit(f"{theirs}: {len(table)} bytes, expected {size}")
        digest = hashlib.sha256(table).hexdigest()
        lines.append(f"// sha256 {digest}")
        lines.append(f"inline constexpr std::array<std::uint8_t, {size}> {ours} = {{{{")
        for start in range(0, size, 16):
            row = ", ".join(f"0x{value:02x}" for value in table[start:start + 16])
            lines.append(f"    {row},")
        lines.append("}};")
        lines.append("")
        print(f"{ours:18} {size:5} bytes  {len(copies)} cop{'y' if len(copies) == 1 else 'ies'} in the reference  sha256 {digest[:16]}")
    output.write_text("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
